"""Forward validation — does the ENGINE predict THIS person's next day?

The existing accuracy journal predicts tomorrow with `statistics.mean(history)` and scores it
against a population constant. That measures whether a person's own average beats a textbook
average (true by construction) — it never calls the simulator. Nothing in the repo currently
tests whether the ENGINE predicts a specific person forward. This does.

The protocol, which is the whole point:

    for each held-out day d:
        1. FIT     parameters on days [1..d-1] ONLY          — day d is never touched
        2. RUN     the engine over day d from that day's LOGGED EVENTS
        3. OBSERVE h(trajectory) -> what the device would report      (simulation.observation)
        4. SCORE   against baselines that must be beaten

Baselines matter more than the metric. Beating a population constant is trivial. The honest
bar is PERSISTENCE — "tomorrow looks like yesterday" — which is brutally strong for anything
slow-moving, and which the current journal never tries.

WHAT THIS DOES AND DOES NOT VALIDATE
------------------------------------
Synthetic days here are generated BY the engine (with a hidden parameter + device noise), so
a fitted engine predicting them is partly circular: it can only show that the plumbing, the
held-out discipline and the fitting recover a truth the engine already assumes. It CANNOT
show the engine is right about a real human — only real CGM + a real food log can do that.

So this validates the HARNESS, not the physiology. It is built now so that the day real data
arrives the measurement is already honest. `test_harness_detects_a_wrong_model` exists for
exactly that reason: a validator that cannot fail is worthless, so we prove it fails when the
model is wrong.

Run:  python -m evaluation.forward_validation
"""

from __future__ import annotations

import statistics
from dataclasses import dataclass

import numpy as np

from simulation import (Simulator, PhysioParams, Schedule, Meal, Drink, Caffeine,
                        Exercise, Sleep)
from simulation.observation import observe_series, spec_for

DAY_MIN = 24 * 60
_PROFILE = {"weight_kg": 82.0, "height_cm": 178.0, "age": 41.0, "sex": "male"}
_POP_GLUCOSE = 100.0          # population-average fasting-ish glucose (the textbook guess)


# --- a day = engine INPUTS (events) + device OUTPUTS (observations) ---------------------

def schedule_from_events(ev: dict) -> Schedule:
    """A logged day -> the stimuli the engine needs. This mapping is the reason an event log
    is the binding constraint on validation: without it there are outputs with no inputs and
    the forward model simply cannot be run."""
    s = Schedule()
    for m in ev.get("meals", []):
        s.add(Meal(float(m["t_min"]), carbs_g=float(m["carbs_g"])))
    for e in ev.get("exercise", []):
        s.add(Exercise(float(e["start_min"]), float(e["end_min"]),
                       intensity_mets=float(e.get("intensity_mets", 6.0))))
    for d in ev.get("drinks", []):
        s.add(Drink(float(d["t_min"]), standard_drinks=float(d["standard_drinks"])))
    for c in ev.get("caffeine", []):
        s.add(Caffeine(float(c["t_min"]), mg=float(c["mg"])))
    for sl in ev.get("sleep", []):
        s.add(Sleep(float(sl["start_min"]), float(sl["end_min"])))
    return s


def _params(insulin_sensitivity: float) -> PhysioParams:
    p = PhysioParams.from_profile(_PROFILE)
    p.insulin_sensitivity = float(np.clip(insulin_sensitivity, 0.05, 3.0))
    return p


def simulate_day(p: PhysioParams, events: dict, dt: float = 1.0):
    # outputs=[glucose] engages modules_for(), so only the 5 modules glucose depends on run
    return Simulator(p).run(schedule_from_events(events), duration_min=DAY_MIN, dt=dt,
                            record_every=5, outputs=["glucose_mg_dl"])


def predict_glucose(p: PhysioParams, events: dict, step_min: float = 5.0) -> list[float]:
    traj = simulate_day(p, events)
    return observe_series(traj, spec_for("cgm", "glucose"), step_min=step_min)["values"]


def synth_days(n_days: int = 12, true_si: float = 0.55, seed: int = 0) -> list[dict]:
    """Days for a person whose TRUE insulin sensitivity is `true_si` (hidden from the fitter),
    observed through a noisy CGM. Meal timing/size jitter day to day, as a real log would."""
    rng = np.random.default_rng(seed)
    p_true = _params(true_si)
    days = []
    for d in range(n_days):
        events = {
            "meals": [
                {"t_min": 8 * 60 + rng.integers(-30, 30), "carbs_g": 45 + rng.integers(-10, 10)},
                {"t_min": 13 * 60 + rng.integers(-40, 40), "carbs_g": 70 + rng.integers(-15, 15)},
                {"t_min": 19 * 60 + rng.integers(-40, 40), "carbs_g": 60 + rng.integers(-15, 15)},
            ],
            "sleep": [{"start_min": 0, "end_min": 7 * 60}],
        }
        traj = simulate_day(p_true, events)
        obs = observe_series(traj, spec_for("cgm", "glucose"), step_min=5.0,
                             rng=rng)                      # device noise ON for the "real" data
        days.append({"date": f"day_{d:02d}", "events": events,
                     "observations": {"glucose": obs}})
    return days


# --- fitting: the first real per-user ENGINE parameter fit ------------------------------

def fit_insulin_sensitivity(days: list[dict], grid: np.ndarray | None = None) -> float:
    """Fit Si by minimising squared error between simulated and observed glucose.

    This is the gap made concrete: `insulin_sensitivity` is otherwise a hardcoded population
    guess (x0.45 if diabetic) and is the most clinically important metabolic knob. A coarse
    1-D grid search is deliberate — it is honest, has no optimiser failure modes, and is the
    baseline any later method (SMC/NPE) must beat.
    """
    grid = np.linspace(0.25, 1.5, 11) if grid is None else grid
    best_si, best_sse = float(grid[0]), float("inf")
    for si in grid:
        p = _params(float(si))
        sse = 0.0
        for day in days:
            obs = day["observations"]["glucose"]["values"]
            pred = predict_glucose(p, day["events"])
            n = min(len(obs), len(pred))
            sse += float(np.sum((np.asarray(obs[:n]) - np.asarray(pred[:n])) ** 2))
        if sse < best_sse:
            best_si, best_sse = float(si), sse
    return best_si


# --- baselines the engine has to beat ---------------------------------------------------

def _mae(a: list[float], b: list[float]) -> float:
    n = min(len(a), len(b))
    return float(np.mean(np.abs(np.asarray(a[:n]) - np.asarray(b[:n])))) if n else float("nan")


@dataclass
class DayScore:
    date: str
    fitted_si: float
    engine_fitted: float
    engine_population: float
    persistence: float
    personal_mean: float
    population_constant: float


def run_forward_validation(days: list[dict], min_history: int = 5,
                           fit_window: int = 3) -> list[DayScore]:
    """Walk the days; every prediction uses ONLY earlier days."""
    scores: list[DayScore] = []
    for d in range(min_history, len(days)):
        train, test = days[:d], days[d]
        actual = test["observations"]["glucose"]["values"]

        si = fit_insulin_sensitivity(train[-fit_window:])          # fit on history only
        pred_fit = predict_glucose(_params(si), test["events"])
        pred_pop = predict_glucose(_params(1.0), test["events"])   # uninformed default

        yesterday = days[d - 1]["observations"]["glucose"]["values"]
        hist_mean = statistics.fmean(
            v for day in train for v in day["observations"]["glucose"]["values"])

        scores.append(DayScore(
            date=test["date"], fitted_si=si,
            engine_fitted=_mae(actual, pred_fit),
            engine_population=_mae(actual, pred_pop),
            persistence=_mae(actual, yesterday),
            personal_mean=_mae(actual, [hist_mean] * len(actual)),
            population_constant=_mae(actual, [_POP_GLUCOSE] * len(actual)),
        ))
    return scores


# --- PRIMARY metric: postprandial response ---------------------------------------------
# Whole-day MAE is the wrong metric for what the engine claims to do. 288 five-minute CGM
# samples are mostly near-fasting baseline, where everyone looks alike, so the meal response
# the engine actually models gets buried: insulin sensitivity being ~2x off moved whole-day
# MAE by only ~1.6 mg/dL. iAUC and peak are the standard CGM meal-response metrics and
# isolate exactly the signal the engine produces.

def postprandial_metrics(values: list[float], t0_min: float, step_min: float,
                         meal_t_min: float, window_min: float = 180.0,
                         baseline_min: float = 30.0) -> dict | None:
    """iAUC + peak for ONE meal — the standard CGM meal-response metrics.

    iAUC is the *incremental* area: trapezoidal integral of max(0, G(t) - baseline) over the
    0-3h window (area below baseline ignored, per convention). Units mg/dL*min.

    The baseline is the MEAN of the pre-meal samples over `baseline_min`, not the single
    reading at t=meal. That matters more than it looks: a lone pre-meal sample carries the
    device's own noise (CGM sigma ~10 mg/dL), and because the baseline is subtracted from
    every point of the integral that error enters COHERENTLY — ~5 min * 36 samples * 10 =
    ~1800 mg/dL*min of pure noise, enough to swamp the model error being measured.
    """
    seg, times, pre = [], [], []
    for i, v in enumerate(values):
        t = t0_min + i * step_min
        if meal_t_min - baseline_min <= t < meal_t_min:
            pre.append(float(v))
        if meal_t_min <= t <= meal_t_min + window_min:
            seg.append(float(v))
            times.append(t)
    if len(seg) < 3:
        return None
    baseline = statistics.fmean(pre) if pre else seg[0]
    incr = [max(0.0, v - baseline) for v in seg]
    # trapezoid on a uniform grid
    iauc = step_min * (sum(incr) - 0.5 * (incr[0] + incr[-1]))
    peak = max(seg)
    peak_time = times[seg.index(peak)] - meal_t_min
    return {"iauc": iauc, "peak": peak, "peak_time_min": peak_time, "baseline": baseline}


@dataclass
class MealScore:
    date: str
    meal_idx: int
    carbs_g: float
    actual_iauc: float
    actual_peak: float
    fitted_iauc_err: float
    population_iauc_err: float
    persistence_iauc_err: float
    personal_mean_iauc_err: float
    fitted_peak_err: float
    persistence_peak_err: float
    fitted_peak_time_err: float


def _meal_metrics(obs: dict, meal_t: float) -> dict | None:
    return postprandial_metrics(obs["values"], obs["t0_min"], obs["step_min"], meal_t)


def run_postprandial_validation(days: list[dict], min_history: int = 5,
                                fit_window: int = 3) -> list[MealScore]:
    """Per-MEAL held-out validation — the primary measure of the engine.

    Persistence here is 'the same meal slot yesterday' (breakfast vs breakfast), which is the
    fair analogue of 'tomorrow looks like yesterday' for a meal response.
    """
    out: list[MealScore] = []
    for d in range(min_history, len(days)):
        train, test = days[:d], days[d]
        actual_obs = test["observations"]["glucose"]
        si = fit_insulin_sensitivity(train[-fit_window:])
        pred_fit = predict_glucose(_params(si), test["events"])
        pred_pop = predict_glucose(_params(1.0), test["events"])
        fit_obs = {"values": pred_fit, "t0_min": 0.0, "step_min": 5.0}
        pop_obs = {"values": pred_pop, "t0_min": 0.0, "step_min": 5.0}

        for mi, meal in enumerate(test["events"]["meals"]):
            t = float(meal["t_min"])
            a = _meal_metrics(actual_obs, t)
            f = _meal_metrics(fit_obs, t)
            p = _meal_metrics(pop_obs, t)
            if not (a and f and p):
                continue

            # persistence: the same meal slot yesterday, at ITS own meal time
            yday = days[d - 1]
            pers = None
            if mi < len(yday["events"]["meals"]):
                pers = _meal_metrics(yday["observations"]["glucose"],
                                     float(yday["events"]["meals"][mi]["t_min"]))

            # personal mean: this meal slot's average iAUC across training days
            hist = [m["iauc"] for day in train
                    if mi < len(day["events"]["meals"])
                    and (m := _meal_metrics(day["observations"]["glucose"],
                                            float(day["events"]["meals"][mi]["t_min"])))]
            pm = statistics.fmean(hist) if hist else float("nan")

            out.append(MealScore(
                date=test["date"], meal_idx=mi, carbs_g=float(meal["carbs_g"]),
                actual_iauc=a["iauc"], actual_peak=a["peak"],
                fitted_iauc_err=abs(a["iauc"] - f["iauc"]),
                population_iauc_err=abs(a["iauc"] - p["iauc"]),
                persistence_iauc_err=abs(a["iauc"] - pers["iauc"]) if pers else float("nan"),
                personal_mean_iauc_err=abs(a["iauc"] - pm),
                fitted_peak_err=abs(a["peak"] - f["peak"]),
                persistence_peak_err=abs(a["peak"] - pers["peak"]) if pers else float("nan"),
                fitted_peak_time_err=abs(a["peak_time_min"] - f["peak_time_min"]),
            ))
    return out


def summarize_postprandial(scores: list[MealScore]) -> dict:
    def m(f):
        vals = [getattr(s, f) for s in scores if not np.isnan(getattr(s, f))]
        return round(statistics.fmean(vals), 1) if vals else float("nan")
    return {"n_meals": len(scores),
            "mean_actual_iauc": m("actual_iauc"),
            "fitted_iauc_mae": m("fitted_iauc_err"),
            "population_iauc_mae": m("population_iauc_err"),
            "persistence_iauc_mae": m("persistence_iauc_err"),
            "personal_mean_iauc_mae": m("personal_mean_iauc_err"),
            "fitted_peak_mae": m("fitted_peak_err"),
            "persistence_peak_mae": m("persistence_peak_err"),
            "fitted_peak_time_mae": m("fitted_peak_time_err")}


def summarize(scores: list[DayScore]) -> dict:
    def m(f):
        return round(statistics.fmean(getattr(s, f) for s in scores), 2)
    return {"n_days": len(scores),
            "fitted_si_mean": round(statistics.fmean(s.fitted_si for s in scores), 3),
            "engine_fitted_mae": m("engine_fitted"),
            "engine_population_mae": m("engine_population"),
            "persistence_mae": m("persistence"),
            "personal_mean_mae": m("personal_mean"),
            "population_constant_mae": m("population_constant")}


def main() -> None:
    import sys
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

    TRUE_SI = 0.55
    days = synth_days(n_days=12, true_si=TRUE_SI, seed=0)
    day_scores = run_forward_validation(days)
    meal_scores = run_postprandial_validation(days)
    s, ps = summarize(day_scores), summarize_postprandial(meal_scores)

    print("=" * 76)
    print("FORWARD VALIDATION — engine vs baselines on HELD-OUT days (CGM glucose)")
    print("=" * 76)
    print(f"  held-out days {s['n_days']} | meals scored {ps['n_meals']}")
    print(f"  true insulin Si {TRUE_SI} (hidden)  ->  fitted {s['fitted_si_mean']}")

    print("\n  PRIMARY — postprandial response (0-3h per meal), the signal the engine models")
    print(f"  {'predictor':<36}{'iAUC MAE':>12}{'mg/dL*min':>11}")
    print(f"  {'-'*59}")
    rows = [("ENGINE (fitted Si)  <- the twin", ps["fitted_iauc_mae"]),
            ("ENGINE (population Si=1.0)", ps["population_iauc_mae"]),
            ("persistence (same meal yesterday)", ps["persistence_iauc_mae"]),
            ("personal mean iAUC for that meal", ps["personal_mean_iauc_mae"])]
    for label, v in sorted(rows, key=lambda r: r[1]):
        print(f"  {label:<36}{v:>12.1f}")
    print(f"\n  mean actual iAUC {ps['mean_actual_iauc']:.0f} mg/dL*min  ->  fitted engine is "
          f"{100*ps['fitted_iauc_mae']/max(ps['mean_actual_iauc'],1e-9):.0f}% off; "
          f"persistence {100*ps['persistence_iauc_mae']/max(ps['mean_actual_iauc'],1e-9):.0f}%")
    print(f"  peak glucose MAE : engine {ps['fitted_peak_mae']:.1f} vs persistence "
          f"{ps['persistence_peak_mae']:.1f} mg/dL")
    print(f"  peak timing MAE  : engine {ps['fitted_peak_time_mae']:.0f} min")

    print("\n  SECONDARY — whole-day MAE (dilutes the signal: mostly fasting baseline)")
    for label, v in sorted([("ENGINE (fitted Si)", s["engine_fitted_mae"]),
                            ("ENGINE (population Si=1.0)", s["engine_population_mae"]),
                            ("persistence (yesterday's curve)", s["persistence_mae"]),
                            ("personal mean glucose", s["personal_mean_mae"]),
                            ("population constant (100 mg/dL)", s["population_constant_mae"])],
                           key=lambda r: r[1]):
        print(f"  {label:<36}{v:>12.2f} mg/dL")

    beat = ps["fitted_iauc_mae"] < ps["persistence_iauc_mae"]
    print(f"\n  engine beats persistence on iAUC: {'YES' if beat else 'NO'} "
          f"({ps['fitted_iauc_mae']:.1f} vs {ps['persistence_iauc_mae']:.1f} mg/dL*min)")
    print("\n  NOTE: these days were generated BY the engine, so this validates the HARNESS")
    print("  (held-out discipline, fitting, baselines) — NOT that the physiology matches a")
    print("  real human. Only real CGM + a real food log can do that.")
    print("=" * 76)


if __name__ == "__main__":
    main()
