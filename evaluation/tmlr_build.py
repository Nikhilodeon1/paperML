"""Build helpers for the TMLR manuscript: placeholders for numbers not yet produced, a to-do check, LaTeX.

* `pending_macros()` writes `paper/pending_macros.tex`: for every `\\res...` macro the manuscript uses and
  `results_macros.tex` does not define, a `\\providecommand` that prints a bold `[pending]`. The paper
  therefore compiles while a result has not been produced, and the gap is visible in the PDF instead of a
  build error or, worse, a blank. A submission has none.
* `check_todos()` counts the `\\todo` and `\\verifycite` markers in the manuscript.
* `compile_latex()` runs latexmk (or pdflatex and bibtex) in `paper/`.

Run:  python -m evaluation.tmlr_build            # pending macros and the to-do count
      python -m evaluation.tmlr_build --compile  # and build paper/main.pdf
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys

from evaluation.results_io import ROOT

PAPER = ROOT / "paper"
USED = re.compile(r"\\(res[A-Za-z]+)")
DEFINED = re.compile(r"\\newcommand\{\\(res[A-Za-z]+)\}")
GENERATED = ("results_macros.tex", "pending_macros.tex", "spec_table.tex", "preamble_defs.tex")


def manuscript_files() -> list:
    return [p for p in sorted(PAPER.glob("*.tex")) if p.name not in GENERATED and p.name != "appendix_deviations.tex"]


def pending_macros() -> list[str]:
    defined = set()
    macros = PAPER / "results_macros.tex"
    if macros.exists():
        defined = set(DEFINED.findall(macros.read_text(encoding="utf-8")))
    used = set()
    for path in manuscript_files():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.lstrip().startswith("%"):
                continue
            used |= set(USED.findall(line))
    missing = sorted(used - defined)
    lines = ["% Generated by evaluation/tmlr_build.py -- DO NOT EDIT.",
             "% Placeholders for result macros the manuscript uses and results_macros.tex does not define yet."]
    lines += [f"\\providecommand{{\\{name}}}{{\\textbf{{[pending]}}}}" for name in missing]
    (PAPER / "pending_macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return missing


def check_todos() -> dict:
    out = {"todo": [], "verifycite": []}
    for path in manuscript_files():
        if path.name == "main.tex":
            continue                      # the macro definitions live there
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            if line.lstrip().startswith("%"):
                continue
            for key in out:
                if f"\\{key}{{" in line:
                    out[key].append(f"{path.name}:{number}")
    return out


def compile_latex() -> int:
    if shutil.which("latexmk"):
        command = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "main.tex"]
        return subprocess.run(command, cwd=PAPER).returncode
    if not shutil.which("pdflatex"):
        print("no LaTeX installation found")
        return 1
    for command in (["pdflatex", "-interaction=nonstopmode", "main.tex"], ["bibtex", "main"],
                    ["pdflatex", "-interaction=nonstopmode", "main.tex"],
                    ["pdflatex", "-interaction=nonstopmode", "main.tex"]):
        code = subprocess.run(command, cwd=PAPER).returncode
        if code and command[0] == "pdflatex":
            return code
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--compile", action="store_true")
    args = ap.parse_args(argv)
    missing = pending_macros()
    print(f"{len(missing)} result macros pending")
    todos = check_todos()
    print(f"{len(todos['todo'])} to-do markers, {len(todos['verifycite'])} citations to verify")
    for key, where in todos.items():
        for w in where:
            print(f"  {key}: {w}")
    if args.compile:
        return compile_latex()
    return 0


if __name__ == "__main__":
    sys.exit(main())
