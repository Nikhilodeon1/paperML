"""REPORTS/final.md: for every hypothesis, the rule as planned, the observed number, and met or not met.

Generated from `evaluation.hypotheses`, so the report cannot drift from the results. A hypothesis that
failed or was not evaluated is listed as such, and the skipped analyses are listed explicitly at the end.

Run:  python -m evaluation.final_report
"""
from __future__ import annotations

import json

from evaluation.hypotheses import evaluate_all, load_summary
from evaluation.results_io import ROOT

OUTPUT = ROOT / "REPORTS" / "final.md"

ALWAYS_SKIPPED = [
    ("A15 design sweep", "Sensitivity-guided design sweep over meal size and timing (reviewer suggestion); "
                         "not run."),
    ("H16", "Heteroskedastic-noise sensitivity of the S_I profile; not run."),
]


def skipped(verdicts: dict) -> list[tuple[str, str]]:
    """What was not run, derived from the verdicts so the list cannot go stale when a job is added."""
    out = list(ALWAYS_SKIPPED)
    for name, text in (("H10", "A8 robustness sweeps (five initializations, three box settings, log versus "
                               "linear parameterization, Adam versus L-BFGS)."),
                       ("H17", "Replica seeds 1 to 4 (the replica result rests on one seed)."),
                       ("H18", "Coordinate profiles on the true-model replica."),
                       ("H19", "Synthetic recovery with random truths (so the synthetic clause of H6)."),
                       ("H20", "Cross-validation on the Shanghai cohort."),
                       ("H21", "Likelihood-optimum check of the coordinate fits."),
                       ("H22", "Second model class (Dalla Man): Fisher matrix and profile intervals.")):
        if verdicts.get(name, {}).get("status") == "not evaluated":
            out.append((name, text))
    return out


def _fmt(value) -> str:
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def _observed(observed: dict, limit: int = 6) -> str:
    items = []
    for key, value in list(observed.items())[:limit]:
        if isinstance(value, dict):
            inner = ", ".join(f"{k}={_fmt(v)}" for k, v in list(value.items())[:4]
                              if not isinstance(v, (dict, list)))
            items.append(f"{key}: {inner}")
        elif not isinstance(value, list):
            items.append(f"{key}={_fmt(value)}")
    return "; ".join(items) if items else "-"


def build() -> str:
    summary = load_summary()
    verdicts = evaluate_all(summary)
    lines = ["# Final report: hypotheses against the analysis plan", "",
             "Generated by `python -m evaluation.final_report` from stored results. The analysis plan was "
             "fixed in version control before the analyses were run; deviations are in "
             "`PREREG_AMENDMENT_1.md`, `_2.md`, `_3.md`. Statuses are comparisons of observed numbers "
             "with the plan's thresholds, not judgements.", ""]
    counts: dict[str, int] = {}
    for row in verdicts.values():
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    lines.append("Summary: " + ", ".join(f"{n} {s}" for s, n in sorted(counts.items())) + ".")
    primary = [k for k, v in verdicts.items() if v["primary"]]
    lines.append("Primary endpoints: " + ", ".join(f"{k} {verdicts[k]['status']}" for k in primary) + ".")
    lines += ["", "| | primary | status | rule in the plan | observed |", "| --- | --- | --- | --- | --- |"]
    for name, row in verdicts.items():
        lines.append(f"| {name} | {'yes' if row['primary'] else ''} | **{row['status']}** | "
                     f"{row['rule']} | {_observed(row['observed'])} |")
    notes = [(n, r["note"]) for n, r in verdicts.items() if r["note"]]
    if notes:
        lines += ["", "## Notes", ""] + [f"* **{n}**: {t}" for n, t in notes]
    lines += ["", "## Failed", ""]
    failed = [n for n, r in verdicts.items() if r["status"] == "not met"]
    lines.append(", ".join(failed) if failed else "None.")
    lines += ["", "## Skipped or not evaluated", ""]
    lines += [f"* **{label}**: {text}" for label, text in skipped(verdicts)]
    lines += ["", "No threshold was changed after the first analysis was run, and no hypothesis was "
              "rescued by changing code or thresholds."]
    return "\n".join(lines) + "\n"


def main() -> int:
    text = build()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
