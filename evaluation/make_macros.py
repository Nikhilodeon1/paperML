"""Generate `paper/results_macros.tex` from the frozen result index.

The rejected submission had its numbers typed into the text by hand, which is how an undefined
error decomposition and a stale table get into a paper at the same time. Here every scalar the
paper quotes is a macro, each macro is emitted from `results/index.json`, and
`evaluation/lint_numbers.py` fails the build if a number is typed in prose instead.

A macro declaration in a result payload looks like one of:

    "macros": {"resLadderIaucCondMedian": 418.2}
    "macros": {"resTableTwoGradMAE": {"value": 1270.4, "fmt": ".0f", "unit": "mg/dL*min"}}
    "macros": {"resGradVsGridDiff": {"value": -12.0, "low": -88.0, "high": 61.0, "fmt": ".0f"}}

An interval expands to three macros: the estimate, `...Low` and `...High`. They are separate
macros on purpose -- a sentence usually wants the estimate alone, and gluing an interval into one
string makes it impossible to typeset it differently in a table.

Macro names must be purely alphabetic: `\\newcommand` does not accept digits or underscores in a
command name, and a name that TeX rejects would fail at build time rather than here.
"""
from __future__ import annotations

import argparse
import json
import math
import re
from pathlib import Path

from evaluation.results_io import ROOT

INDEX = ROOT / "results" / "index.json"
OUTPUT = ROOT / "paper" / "results_macros.tex"

_NAME = re.compile(r"^[A-Za-z]+$")
DEFAULT_FMT = ".3g"


def _format(value, fmt: str) -> str:
    if value is None:
        return r"\textbf{??}"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, str):
        return value
    number = float(value)
    if math.isnan(number):
        return r"\textbf{NaN}"
    if math.isinf(number):
        return r"$\infty$" if number > 0 else r"$-\infty$"
    return format(number, fmt)


def _expand(name: str, spec) -> list[tuple[str, str]]:
    """One declaration to its `(macro name, rendered value)` pairs."""
    entry = spec if isinstance(spec, dict) else {"value": spec}
    fmt = entry.get("fmt", DEFAULT_FMT)
    out = [(name, _format(entry.get("value"), fmt))]
    if entry.get("low") is not None:
        out.append((name + "Low", _format(entry["low"], fmt)))
    if entry.get("high") is not None:
        out.append((name + "High", _format(entry["high"], fmt)))
    return out


def build(index_path: Path | None = None) -> tuple[str, int]:
    # Resolved at call time, not bound as a default, so a test or an alternative results
    # directory can redirect the module constant.
    index_path = INDEX if index_path is None else index_path
    if not index_path.exists():
        raise SystemExit(f"{index_path} does not exist; run evaluation.freeze_results first.")
    index = json.loads(index_path.read_text(encoding="utf-8"))
    macros = index.get("macros", {})

    bad = [n for n in macros if not _NAME.match(n)]
    if bad:
        raise SystemExit("Macro names must be alphabetic only (TeX restriction); offending: "
                         + ", ".join(sorted(bad)))

    lines = [
        "% Generated by evaluation/make_macros.py from results/index.json -- DO NOT EDIT.",
        f"% commit {index.get('commit')}  frozen {index.get('frozen_at')}",
        f"% result files {index.get('n_files')}  combined sha256 {index.get('sha256_over_all')}",
        "",
    ]
    count = 0
    for name in sorted(macros):
        entry = macros[name] if isinstance(macros[name], dict) else {"value": macros[name]}
        note = " ".join(str(entry[k]) for k in ("unit", "analysis_id") if entry.get(k))
        for macro, rendered in _expand(name, macros[name]):
            lines.append(f"\\newcommand{{\\{macro}}}{{{rendered}}}"
                         + (f"  % {note}" if note else ""))
            count += 1
    return "\n".join(lines) + "\n", count


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--output", type=Path, default=OUTPUT)
    args = ap.parse_args()
    text, count = build()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {count} macros to {args.output}")


if __name__ == "__main__":
    main()
